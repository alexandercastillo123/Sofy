    def only_numeric_input(self, P):

        # Verifica si la cadena está vacía o si es numérica o un punto, y que solo haya un solo punto
        if P.isdigit() or (P.count('.') <= 1 and all(c.isdigit() or c == '.' for c in P)):
            return True
        else:
            return False
    
    def only_grados_input(self, P):
        # Permite que el campo esté vacío temporalmente
        if P == "":
                return True
        # Verifica que la cadena sea numérica o tenga un punto, con a lo más un solo punto
        if P.replace('.', '', 1).isdigit() and P.count('.') <= 1:
 
            number = float(P)
            # Comprueba que el número esté dentro del rango permitido de 0 a 90
            if 0 <= number <= 90:
                return True
        return False